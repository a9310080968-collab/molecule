type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (source: string, params?: TranslationParams) => string;
  system: (value: string | undefined) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window === "undefined") {
      return "ru";
    }
    const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
    if (requestedLanguage === "ru" || requestedLanguage === "en") {
      return requestedLanguage;
    }
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "en" ? "en" : "ru";
  });

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.title = language === "en" ? "2D documentation map | Molecule" : "2D-карта документации | Молекула";
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (source, params) => translate(source, language, params),
    system: (text) => localizeSystemText(text, language),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}

export function translate(source: string, language: Language, params?: TranslationParams) {
  const template = language === "en" ? english[source] ?? source : source;
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce(
    (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
    template,
  );
}

export function localizeSystemText(value: string | undefined, language: Language): string {
  if (!value || language === "ru") {
    return value ?? "";
  }
  if (english[value]) {
    return english[value];
  }

  const deadlineDescription = value.match(/^(.*): ([→←]) (.+)\. Передает: (.*); получает: (.*); согласует: (.*)\.$/);
  if (deadlineDescription) {
    const finalStop = deadlineDescription[6].endsWith(".") ? "" : ".";
    return `${deadlineDescription[1]}: ${deadlineDescription[2]} ${localizeSystemText(deadlineDescription[3], language)}. Sender: ${deadlineDescription[4]}; recipient: ${deadlineDescription[5]}; approver: ${deadlineDescription[6]}${finalStop}`;
  }

  const clarification = value.match(/^(.*?): (.*?) просит уточнить «(.*?)»\. (.*)$/);
  if (clarification) {
    return `${clarification[1]}: ${clarification[2]} asks to clarify \"${clarification[3]}\". ${localizeSystemText(clarification[4], language)}`;
  }

  const chatClarification = value.match(/^(Задание непонятно|Вопрос по заданию) «(.*?)»: (.*)$/);
  if (chatClarification) {
    return `${english[chatClarification[1]] ?? chatClarification[1]} \"${chatClarification[2]}\": ${localizeSystemText(chatClarification[3], language)}`;
  }

  const tagMatch = value.match(/^Тег «(.*?)» совпал с нодой «(.*?)»\.$/);
  if (tagMatch) {
    return `Tag \"${tagMatch[1]}\" matched node \"${tagMatch[2]}\".`;
  }

  const integrationTitle = value.match(/^Новые файлы из (.*)$/);
  if (integrationTitle) {
    return `New files from ${localizeSystemText(integrationTitle[1], language)}`;
  }

  const integrationDescription = value.match(/^(.*?) получил\(а\) (\d+) файл\(а\): (\d+) распределено по тегам, (\d+) во входящих\.$/);
  if (integrationDescription) {
    return `${integrationDescription[1]} received ${integrationDescription[2]} files: ${integrationDescription[3]} routed by tag, ${integrationDescription[4]} incoming.`;
  }

  const processSent = value.match(/^Маршрут «(.*?)» собран в конструкторе и отправлен на проверку\.$/);
  if (processSent) {
    return `Route \"${processSent[1]}\" was configured in the builder and sent for review.`;
  }

  const rejectedFile = value.match(/^Файл «(.*?)» выброшен наружу для доработки\.$/);
  if (rejectedFile) {
    return `File \"${rejectedFile[1]}\" was moved outside for revision.`;
  }

  const attachmentAdded = value.match(/^Вложение добавлено в контейнер «(.*?)»\.$/);
  if (attachmentAdded) {
    return `Attachment added to container \"${attachmentAdded[1]}\".`;
  }

  const acceptedContainer = value.match(/^Принял контейнер «(.*?)» в работу, жду финальный комплект\.$/);
  if (acceptedContainer) {
    return `Accepted container \"${acceptedContainer[1]}\" for work; waiting for the final package.`;
  }

  const fileSize = value.match(/^(\d+(?:[.,]\d+)?)\s*(Б|КБ|МБ|ГБ)$/i);
  if (fileSize) {
    const units: Record<string, string> = { "Б": "B", "КБ": "KB", "МБ": "MB", "ГБ": "GB" };
    return `${fileSize[1]} ${units[fileSize[2].toUpperCase()] ?? fileSize[2]}`;
  }

  return value
    .replace(/(просрочено|осталось) (\d+) (мин|ч|д)/gi, (_, state: string, count: string, sourceUnit: string) => {
      const unit = sourceUnit.toLowerCase() === "мин" ? "min" : sourceUnit.toLowerCase() === "ч" ? "h" : "d";
      return `${state.toLowerCase() === "просрочено" ? "overdue by" : "remaining"} ${count} ${unit}`;
    })
    .replace(/^только что$/i, "just now")
    .replace(/^сегодня(?=\b|,)/i, "today")
    .replace(/^завтра(?=\b|,)/i, "tomorrow")
    .replace(/^вчера(?=\b|,)/i, "yesterday");
}
